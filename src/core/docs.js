export function keyDoc(key, parentType) {
  if (parentType) {
    const base = parentType.split('/')[0]
    const c = CTX_DOCS[`${parentType}:${key}`] || CTX_DOCS[`${base}:${key}`]
    if (c) return c
  }
  return KEY_DOCS[key] || ''
}

